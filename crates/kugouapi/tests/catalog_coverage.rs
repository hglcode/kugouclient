#[test]
fn catalog_covers_the_reference_endpoint_list() {
    let registered = kugouapi::catalog::endpoint_ids();
    assert_eq!(
        registered.len(),
        EXPECTED_ENDPOINT_IDS.len(),
        "endpoint count drifted from the reference catalog"
    );

    let registered: std::collections::HashSet<&str> = registered.iter().copied().collect();
    let expected: std::collections::HashSet<&str> = EXPECTED_ENDPOINT_IDS.iter().copied().collect();

    let missing: Vec<&str> = EXPECTED_ENDPOINT_IDS
        .iter()
        .filter(|id| !registered.contains(**id))
        .copied()
        .collect();
    assert!(missing.is_empty(), "missing endpoints: {missing:?}");

    let extra: Vec<&str> = registered
        .iter()
        .filter(|id| !expected.contains(*id))
        .copied()
        .collect();
    assert!(extra.is_empty(), "unregistered endpoints: {extra:?}");
}

#[test]
fn endpoint_count_constant_matches() {
    assert_eq!(
        kugouapi::catalog::ENDPOINT_COUNT,
        kugouapi::catalog::endpoint_ids().len()
    );
}
